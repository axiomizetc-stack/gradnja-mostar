function applyLanguage(lang) {
  const pack = translations[lang] || translations.bs;
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.getAttribute("data-i18n");
    if (pack[key]) node.textContent = pack[key];
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    const key = node.getAttribute("data-i18n-placeholder");
    if (pack[key]) node.setAttribute("placeholder", pack[key]);
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((node) => {
    const key = node.getAttribute("data-i18n-aria");
    if (pack[key]) node.setAttribute("aria-label", pack[key]);
  });
  document.querySelectorAll(".lang button").forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.lang === lang));
  });
  localStorage.setItem("gradnja-lang", lang);
}

document.querySelectorAll(".lang button").forEach((button) => {
  button.addEventListener("click", () => applyLanguage(button.dataset.lang));
});

applyLanguage(localStorage.getItem("gradnja-lang") || "bs");

const header = document.querySelector(".site-header");
const toggle = document.querySelector(".menu-toggle");
toggle?.addEventListener("click", () => {
  const open = header.classList.toggle("is-open");
  toggle.setAttribute("aria-expanded", String(open));
});

document.querySelectorAll("#nav a").forEach((link) => {
  link.addEventListener("click", () => {
    header.classList.remove("is-open");
    toggle?.setAttribute("aria-expanded", "false");
  });
});

const slides = [...document.querySelectorAll(".hero-slides figure")];
const dotsWrap = document.querySelector(".hero-dots");
let slideIndex = 0;
let slideTimer;

function showSlide(index) {
  if (!slides.length) return;
  slideIndex = (index + slides.length) % slides.length;
  slides.forEach((slide, i) => slide.classList.toggle("is-active", i === slideIndex));
  dotsWrap?.querySelectorAll("button").forEach((dot, i) => {
    dot.setAttribute("aria-selected", String(i === slideIndex));
  });
}

function startSlides() {
  clearInterval(slideTimer);
  slideTimer = setInterval(() => showSlide(slideIndex + 1), 6500);
}

if (slides.length && dotsWrap) {
  slides.forEach((_, i) => {
    const dot = document.createElement("button");
    dot.type = "button";
    dot.setAttribute("aria-label", `Slika ${i + 1}`);
    dot.addEventListener("click", () => {
      showSlide(i);
      startSlides();
    });
    dotsWrap.append(dot);
  });
  document.querySelector(".hero-nav.prev")?.addEventListener("click", () => {
    showSlide(slideIndex - 1);
    startSlides();
  });
  document.querySelector(".hero-nav.next")?.addEventListener("click", () => {
    showSlide(slideIndex + 1);
    startSlides();
  });
  showSlide(0);
  startSlides();
}

document.getElementById("order-form")?.addEventListener("submit", (event) => {
  event.preventDefault();
  const form = event.currentTarget;
  const status = document.getElementById("form-status");
  const lang = localStorage.getItem("gradnja-lang") || "bs";
  const data = new FormData(form);
  const name = String(data.get("name") || "").trim();
  const phone = String(data.get("phone") || "").trim();
  const type = String(data.get("type") || "other");
  const message = String(data.get("message") || "").trim();

  if (!name || !phone) {
    status.textContent = translations[lang].form.error;
    return;
  }

  const typeText = typeLabels[lang][type] || type;
  const body =
    lang === "en"
      ? `Hello Gradnja Mostar, I am ${name}. Phone: ${phone}. Request: ${typeText}. ${message}`
      : `Zdravo Gradnja Mostar, ja sam ${name}. Telefon: ${phone}. Tražim: ${typeText}. ${message}`;

  status.textContent = "";
  window.open(`https://wa.me/38761209379?text=${encodeURIComponent(body)}`, "_blank", "noopener,noreferrer");
});
